import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

export const DERIVED_SLOTS = new Set([
	"statusTerminated",
	"sidebarBorder",
	"bgPrimary",
	"bgSecondary",
	"bgTertiary",
	"bgElevated",
	"bgSidebar",
	"textPrimary",
	"textMuted",
	"textPassive",
	"colorBorder",
	"borderStrong",
	"colorAccent",
	"colorAccentForeground",
	"dangerStrong",
	"statusIdle",
	"statusExited",
	"warning",
	"success",
	"danger",
]);

const TOKENS = path.resolve("src/styles/tokens.css");
const NON_COLOUR = /^--(size|space|radius|font|tracking|leading|z|duration|ease|breakpoint)/;

// `--color-` is a namespace prefix, not part of the name: --color-status-working
// and --background must both yield a usable slot name.
function camel(cssVar) {
	return cssVar
		.replace(/^--(color-)?/, "")
		.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

// `--accent`, `--accent-foreground`, `--accent-weak`, `--border`,
// `--interactive-hover`, and `--interactive-active` already have the plain
// camelCase slot names elsewhere in the codebase (they're the "primary"
// identity tokens), so the `--color-*` siblings that would otherwise
// collapse to the same slot after camel() strips the `--color-` namespace
// keep their namespace in the slot name instead. `--color-accent-dim` and
// `--color-accent-strong` don't collide with anything, but get the same
// namespaced treatment for consistency with their `--color-accent-*` siblings.
const SLOT_OVERRIDES = {
	"--color-accent": "colorAccent",
	"--color-accent-foreground": "colorAccentForeground",
	"--color-accent-weak": "colorAccentWeak",
	"--color-accent-dim": "colorAccentDim",
	"--color-accent-strong": "colorAccentStrong",
	"--color-border": "colorBorder",
	"--color-interactive-hover": "colorInteractiveHover",
	"--color-interactive-active": "colorInteractiveActive",
};

function slotName(cssVar) {
	return SLOT_OVERRIDES[cssVar] ?? camel(cssVar);
}

function assertNoCollisions(cssVars) {
	const seen = new Map();
	for (const cssVar of cssVars) {
		const slot = slotName(cssVar);
		if (seen.has(slot)) {
			throw new Error(`slot name collision: ${slot} <- ${seen.get(slot)} and ${cssVar}`);
		}
		seen.set(slot, cssVar);
	}
}

// tokens.css opens with a header doc comment that mentions the real
// selectors as prose (e.g. `:root[data-theme="light"]`), so a bare
// `indexOf(selector)` can match inside the comment instead of the real
// rule. Anchor every lookup past the header comment.
function headerEnd(css) {
	const end = css.indexOf("*/");
	return end === -1 ? 0 : end + 2;
}

export function parseBlock(css, selector) {
	const start = css.indexOf(selector, headerEnd(css));
	if (start === -1) throw new Error(`selector not found: ${selector}`);
	const open = css.indexOf("{", start);
	const close = css.indexOf("\n}", open);
	const body = css.slice(open + 1, close);
	const out = {};
	for (const line of body.split("\n")) {
		const match = line.match(/^\s*(--[a-z0-9-]+)\s*:\s*(.+?);/);
		if (!match) continue;
		const [, name, value] = match;
		if (NON_COLOUR.test(name)) continue;
		out[name] = value.trim();
	}
	return out;
}

const css = await readFile(TOKENS, "utf8");
const base = parseBlock(css, ":root,\n:root.dark,\n.dark");
assertNoCollisions(Object.keys(base));
const entries = Object.keys(base)
	.sort()
	.map((v) => `\t${slotName(v)}: "${v}",`);

await writeFile(
	path.resolve("src/renderer/theme/token-map.generated.ts"),
	`// Generated by scripts/extract-skin-tokens.mjs. Do not edit.\n` +
		`export const SKIN_TOKENS = {\n${entries.join("\n")}\n} as const;\n\n` +
		`export type SlotName = keyof typeof SKIN_TOKENS;\n`,
);

console.log(`wrote ${Object.keys(base).length} tokens`);

// Derived slots are dropped here so a skin never carries a stale copy of a
// value app-skin.ts recomputes from its source slot.
function skinBody(values) {
	return Object.entries(values)
		.filter(([cssVar]) => !DERIVED_SLOTS.has(slotName(cssVar)))
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([cssVar, value]) => `\t${slotName(cssVar)}: "${value}",`)
		.join("\n");
}

function emitSkin(name, values, importPath = "../app-skin") {
	return (
		`// Generated by scripts/extract-skin-tokens.mjs. Do not edit.\n` +
		`import { defineSkin } from "${importPath}";\n\n` +
		`export const ${name} = defineSkin({\n${skinBody(values)}\n});\n`
	);
}

// A named style's generated half is plain token data, not a resolved skin: the
// hand-written `{style}.ts` layers that palette's status and ANSI colours on
// top before calling defineSkin, so the derived slots resolve against the
// final values rather than the generated ones.
function emitTokens(name, values) {
	return `export const ${name} = {\n${skinBody(values)}\n} as const;\n`;
}

const light = parseBlock(css, ':root[data-theme="light"]');
await writeFile(path.resolve("src/renderer/theme/skins/dark.ts"), emitSkin("darkSkin", base));
await writeFile(
	path.resolve("src/renderer/theme/skins/light.ts"),
	emitSkin("lightSkin", { ...base, ...light }),
);
console.log(`wrote dark (${Object.keys(base).length}) and light (${Object.keys(light).length} overrides)`);

// The layering reproduces today's cascade: a dark named document matches
// `:root` then `:root[data-style-theme="X"]`; a light one also matches
// `:root[data-theme="light"]` (less specific than the style block) and
// finally `:root[data-style-theme="X"][data-theme="light"]`.
const STYLES = [
	"github",
	"catppuccin",
	"dracula",
	"tokyo-night",
	"rose-pine",
	"nord",
	"gruvbox",
	"solarized",
];

for (const style of STYLES) {
	const styleDark = parseBlock(css, `:root[data-style-theme="${style}"]`);
	const styleLight = parseBlock(css, `:root[data-style-theme="${style}"][data-theme="light"]`);
	const name = style.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
	await writeFile(
		path.resolve(`src/renderer/theme/skins/${style}.generated.ts`),
		`// Generated by scripts/extract-skin-tokens.mjs. Do not edit.\n` +
			`// Palette overrides live in ./${style}.ts.\n\n` +
			emitTokens(`${name}DarkTokens`, { ...base, ...styleDark }) +
			"\n" +
			emitTokens(`${name}LightTokens`, { ...base, ...light, ...styleDark, ...styleLight }),
	);
	console.log(`wrote ${style} (${Object.keys(styleDark).length} dark overrides)`);
}
